using Dreamness.Ra3.Map.Parser.Core.Map;
using System.Text.Json;
using System.Text.Encodings.Web;
var opts=new JsonSerializerOptions{WriteIndented=true,IncludeFields=true,Encoder=JavaScriptEncoder.UnsafeRelaxedJsonEscaping};
if(args.Length<2)throw new ArgumentException("Usage: Editor input.map output.map [report-directory]");
var input=Path.GetFullPath(args[0]);
var output=Path.GetFullPath(args[1]);
var reportDir=Path.GetFullPath(args.Length>2?args[2]:Path.Combine(Path.GetDirectoryName(output)!,"reports"));
Directory.CreateDirectory(reportDir);
var map=Ra3Map.Open(input);
var c=map.Context;
if(map.Errored)throw new Exception("Original map parsed with errors.");
var terrain=TerrainExpansion.ExpandRight(map);
var players=PlayersExpansion.Apply(map);
var objects=ObjectsExpansion.Apply(c);
var metadata=MetadataExpansion.Expand(map);
var scripts=ScriptsExpansion.Expand(map,Path.Combine(reportDir,"script-wire-audit.json"));
Console.WriteLine(scripts);
map.SaveAs(output,true);
var reopened=Ra3Map.Open(output);
if(reopened.Errored)throw new Exception("Saved map parsed with errors.");
MetadataExpansion.Validate(reopened.Context);
File.WriteAllText(Path.Combine(reportDir,"final-scripts.json"),reopened.Context.ExportPlayerScriptsListToJson());
MetadataExpansion.ExportPreviewData(reopened.Context,Path.Combine(reportDir,"final-preview"));
File.WriteAllText(Path.Combine(reportDir,"final-objects.json"),JsonSerializer.Serialize(reopened.Context.ObjectsListAsset.MapObjectList.Select(o=>new{o.TypeName,o.Position,o.Angle,o.RoadOption,Properties=o.Properties.PropertiesDict.ToDictionary(k=>k.Key,k=>k.Value.Value)}),opts));
File.WriteAllText(Path.Combine(reportDir,"build-report.json"),JsonSerializer.Serialize(new{terrain,players,objects,metadata},opts));
Console.WriteLine(JsonSerializer.Serialize(new{terrain,players,addedObjects=objects.Added.Count,movedObjects=objects.Moved,metadata},opts));
